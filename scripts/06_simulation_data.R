# ==================================================================================================
# 1. SIMULATE ONE CLUSTER
# ==================================================================================================

simulate_one_cluster <- function(
    cluster_id,
    p,
    disc = FALSE,
    cuts_x,
    cuts_y
) {
  
  # -----------------------------------------------------------------------------------------------
  # Cluster-level latent variables U and V
  # -----------------------------------------------------------------------------------------------
  
  Sigma_uv <- matrix(
    c(
      p$sigma_u^2,
      p$sigma_u * p$sigma_v * p$rho_uv,
      p$sigma_u * p$sigma_v * p$rho_uv,
      p$sigma_v^2
    ),
    nrow = 2
  )
  
  uv <- matrix(
    MASS::mvrnorm(
      n = 1,
      mu = c(
        p$mu_u,
        p$mu_v
      ),
      Sigma = Sigma_uv
    )
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Tooth-level X and Y
  # -----------------------------------------------------------------------------------------------
  
  Sigma_xy <- matrix(
    c(
      p$sigma_x^2,
      p$sigma_x * p$sigma_y * p$rho_xy,
      p$sigma_x * p$sigma_y * p$rho_xy,
      p$sigma_y^2
    ),
    ncol = 2
  )
  
  xy <- matrix(
    MASS::mvrnorm(
      n = p$nmax,
      mu = c(
        p$alpha_x + p$beta_x * uv[1],
        p$alpha_y + p$beta_y * uv[2]
      ),
      Sigma = Sigma_xy
    ),
    ncol = 2
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Standardized X and Y
  # -----------------------------------------------------------------------------------------------
  
  x_std <- (
    xy[, 1] - (p$alpha_x + p$beta_x * p$mu_u)
  ) / sqrt(
    p$beta_x^2 * p$sigma_u^2 + p$sigma_x^2
  )
  
  y_std <- (
    xy[, 2] - (p$alpha_y + p$beta_y * p$mu_v)
  ) / sqrt(
    p$beta_y^2 * p$sigma_v^2 + p$sigma_y^2
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Severity categories
  # -----------------------------------------------------------------------------------------------
  
  if (p$tau_x == 1) {
    
    z_x <- 0
    
  } else {
    
    z_x <- p$tau_x - cut(
      x_std,
      breaks = cuts_x,
      labels = FALSE,
      right = FALSE
    )
  }
  
  
  if (p$tau_y == 1) {
    
    z_y <- 0
    
  } else {
    
    z_y <- p$tau_y - cut(
      y_std,
      breaks = cuts_y,
      labels = FALSE,
      right = FALSE
    )
  }
  
  
  # -----------------------------------------------------------------------------------------------
  # Probability of tooth retention
  # -----------------------------------------------------------------------------------------------
  
  Rij <- pmin(
    plogis(
      p$eta_0 + p$eta_x * xy[, 1]
    ),
    plogis(
      p$eta_0 + p$eta_y * xy[, 2]
    )
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Retention indicator
  # -----------------------------------------------------------------------------------------------
  
  n_idx <- sapply(
    Rij,
    function(j) {
      
      rbinom(
        n = 1,
        size = 1,
        prob = j
      )
    }
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Return cluster
  # -----------------------------------------------------------------------------------------------
  
  data.frame(
    cluster = cluster_id,
    size = sum(n_idx == 1),
    j = seq_len(p$nmax),
    X = xy[, 1],
    Y = xy[, 2],
    U = uv[1],
    V = uv[2],
    R = n_idx,
    X_sev = z_x,
    Y_sev = z_y,
    Prob_R = Rij
  )
}


# ==================================================================================================
# 2. SIMULATE ONE DATASET
# ==================================================================================================

simulate_dataset <- function(
    M,
    p,
    d,
    seed = NULL
) {
  
  if (!is.null(seed)) {
    set.seed(seed)
  }
  
  
  # -----------------------------------------------------------------------------------------------
  # Severity cut points
  # -----------------------------------------------------------------------------------------------
  
  cuts_x <- c(
    -Inf,
    qnorm(
      seq(1, p$tau_x - 1) / p$tau_x
    ),
    Inf
  )
  
  cuts_y <- c(
    -Inf,
    qnorm(
      seq(1, p$tau_y - 1) / p$tau_y
    ),
    Inf
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Simulate clusters
  # -----------------------------------------------------------------------------------------------
  
  dat <- do.call(
    rbind,
    lapply(
      seq_len(M),
      function(i) {
        
        simulate_one_cluster(
          cluster_id = i,
          p = p,
          disc = d,
          cuts_x = cuts_x,
          cuts_y = cuts_y
        )
      }
    )
  )
  
  
  return(dat)
}


# ==================================================================================================
# 3. HELPER FUNCTION FOR FILE LABELS
# ==================================================================================================

make_label <- function(x) {
  
  x <- format(
    x,
    scientific = FALSE,
    trim = TRUE
  )
  
  x <- gsub(
    "-",
    "m",
    x
  )
  
  x <- gsub(
    "\\.",
    "p",
    x
  )
  
  return(x)
}


# ==================================================================================================
# 4. SIMULATE REPLICATES FOR ONE SCENARIO
# ==================================================================================================

simulate_replicates <- function(
    M,
    p,
    d,
    n_reps = 1000,
    base_seed = 1,
    save_dir = ".",
    chunk_size = 500
) {
  
  # -----------------------------------------------------------------------------------------------
  # Scenario label
  # -----------------------------------------------------------------------------------------------
  
  sim_label <- paste0(
    "rxy_", make_label(p$rho_xy),
    "_ruv_", make_label(p$rho_uv),
    "_etax_", make_label(p$eta_x),
    "_etay_", make_label(p$eta_y),
    "_M_", M
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Number of output chunks
  # -----------------------------------------------------------------------------------------------
  
  n_chunks <- ceiling(
    n_reps / chunk_size
  )
  
  out_files <- vector(
    "character",
    n_chunks
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Run simulation chunks
  # -----------------------------------------------------------------------------------------------
  
  for (chunk_id in seq_len(n_chunks)) {
    
    rep_start <- (chunk_id - 1) * chunk_size + 1
    
    rep_end <- min(
      chunk_id * chunk_size,
      n_reps
    )
    
    reps_this_chunk <- rep_start:rep_end
    
    
    # ---------------------------------------------------------------------------------------------
    # Storage for replicates in this chunk
    # ---------------------------------------------------------------------------------------------
    
    reps <- vector(
      "list",
      length(reps_this_chunk)
    )
    
    
    # ---------------------------------------------------------------------------------------------
    # Simulate replicates
    # ---------------------------------------------------------------------------------------------
    
    for (k in seq_along(reps_this_chunk)) {
      
      b <- reps_this_chunk[k]
      
      reps[[k]] <- simulate_dataset(
        M = M,
        p = p,
        d = d,
        seed = base_seed + b - 1
      )
      
      reps[[k]]$replicate <- b
    }
    
    
    # ---------------------------------------------------------------------------------------------
    # Output filename
    # ---------------------------------------------------------------------------------------------
    
    out_file <- file.path(
      save_dir,
      paste0(
        "sim_reps_",
        sim_label,
        "_",
        chunk_id,
        ".rds"
      )
    )
    
    
    # ---------------------------------------------------------------------------------------------
    # Saved simulation object
    # ---------------------------------------------------------------------------------------------
    
    out <- list(
      label = sim_label,
      M = M,
      n_reps_total = n_reps,
      chunk_id = chunk_id,
      chunk_size = chunk_size,
      rep_start = rep_start,
      rep_end = rep_end,
      base_seed = base_seed,
      seeds = base_seed + reps_this_chunk - 1,
      params = p,
      disc = d,
      data = reps
    )
    
    
    # ---------------------------------------------------------------------------------------------
    # Save chunk
    # ---------------------------------------------------------------------------------------------
    
    saveRDS(
      out,
      out_file
    )
    
    out_files[chunk_id] <- out_file
    
    
    cat(
      "Saved chunk",
      chunk_id,
      "of",
      n_chunks,
      "\n"
    )
    
    cat(
      "Saved:",
      out_file,
      "\n\n"
    )
    
    
    rm(
      reps,
      out
    )
    
    gc()
  }
  
  
  invisible(out_files)
}


# ==================================================================================================
# 5. GLOBAL SIMULATION PARAMETERS
# ==================================================================================================

params <- list(
  
  # -----------------------------------------------------------------------------------------------
  # Maximum cluster size
  # -----------------------------------------------------------------------------------------------
  
  nmax = 10,
  
  
  # -----------------------------------------------------------------------------------------------
  # Cluster-level latent parameters
  # -----------------------------------------------------------------------------------------------
  
  mu_u = 0,
  mu_v = 0,
  
  sigma_u = 1,
  sigma_v = 1,
  
  rho_uv = 0.5,
  
  
  # -----------------------------------------------------------------------------------------------
  # Tooth-level latent parameters
  # -----------------------------------------------------------------------------------------------
  
  alpha_x = 0,
  alpha_y = 0,
  
  beta_x = 1,
  beta_y = 1,
  
  sigma_x = 0.5,
  sigma_y = 0.5,
  
  rho_xy = 0.5,
  
  
  # -----------------------------------------------------------------------------------------------
  # Discretization
  # -----------------------------------------------------------------------------------------------
  
  tau_x = 5,
  tau_y = 5,
  
  
  # -----------------------------------------------------------------------------------------------
  # Retention
  # -----------------------------------------------------------------------------------------------
  
  eta_0 = 3,
  
  eta_x = 4,
  eta_y = 4
)


# ==================================================================================================
# 6. SIMULATION GRID
# ==================================================================================================

grid <- expand.grid(
  eta_x  = c(0, 4),
  eta_y  = c(0, 4),
  rho_xy = c(0, 0.5),
  rho_uv = c(0, 0.5),
  M      = c(20),
  KEEP.OUT.ATTRS = FALSE
)


