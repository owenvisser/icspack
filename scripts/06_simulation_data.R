# Small test simulation

reps <- 100


# Save 100 replicates in each RDS file - can be adjusted later on.

chunk_size <- 100


# Number of parallel scenario workers.
#
# Start conservatively on the local computer.

cores <- 4


# ==================================================================================================
# 9. RUN ONE GRID SCENARIO
# ==================================================================================================

run_one_grid_scenario <- function(s) {
  
  # -----------------------------------------------------------------------------------------------
  # Copy parameters
  # -----------------------------------------------------------------------------------------------
  
  p_s <- params
  
  
  # -----------------------------------------------------------------------------------------------
  # Scenario-specific parameters
  # -----------------------------------------------------------------------------------------------
  
  p_s$eta_y  <- grid$eta_y[s]
  p_s$eta_x  <- grid$eta_x[s]
  p_s$rho_xy <- grid$rho_xy[s]
  p_s$rho_uv <- grid$rho_uv[s]
  
  
  # -----------------------------------------------------------------------------------------------
  # Print scenario information
  # -----------------------------------------------------------------------------------------------
  
  cat(
    "\n============================================================\n"
  )
  
  cat(
    "Starting scenario",
    s,
    "of",
    nrow(grid),
    "\n"
  )
  
  cat(
    "============================================================\n"
  )
  
  cat("eta_y:", p_s$eta_y, "\n")
  cat("eta_x:", p_s$eta_x, "\n")
  cat("rho_xy:", p_s$rho_xy, "\n")
  cat("rho_uv:", p_s$rho_uv, "\n")
  cat("M:", grid$M[s], "\n\n")
  
  
  # -----------------------------------------------------------------------------------------------
  # Run scenario
  # -----------------------------------------------------------------------------------------------
  
  out_files_s <- simulate_replicates(
    M = grid$M[s],
    p = p_s,
    d = FALSE,
    n_reps = reps,
    base_seed = 100000 * s + 1,
    save_dir = save_dir,
    chunk_size = chunk_size
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Scenario complete
  # -----------------------------------------------------------------------------------------------
  
  cat(
    "Finished scenario",
    s,
    "of",
    nrow(grid),
    "\n\n"
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Return scenario index
  # -----------------------------------------------------------------------------------------------
  
  data.frame(
    scenario = s,
    eta_y = p_s$eta_y,
    eta_x = p_s$eta_x,
    rho_xy = p_s$rho_xy,
    rho_uv = p_s$rho_uv,
    M = grid$M[s],
    chunk_id = seq_along(out_files_s),
    out_file = out_files_s
  )
}

# ==================================================================================================
# 10. RUN SIMULATION GRID IN PARALLEL
# ==================================================================================================

run_parallel_simulation <- function() {
  
  # -----------------------------------------------------------------------------------------------
  # Create PSOCK cluster
  # -----------------------------------------------------------------------------------------------
  
  cl <- parallel::makeCluster(
    cores,
    type = "PSOCK",
    rscript_args = "--vanilla"
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # ALWAYS close cluster when this function exits
  #
  # This runs if:
  #   - the simulation completes normally
  #   - an error occurs
  #   - execution is interrupted normally by R
  # -----------------------------------------------------------------------------------------------
  
  on.exit(
    {
      cat("\nClosing parallel workers...\n")
      
      try(
        parallel::stopCluster(cl),
        silent = TRUE
      )
      
      rm(cl)
      gc()
      
      cat("Parallel workers closed.\n")
    },
    add = TRUE
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Export required objects and functions
  # -----------------------------------------------------------------------------------------------
  
  parallel::clusterExport(
    cl,
    varlist = c(
      "params",
      "grid",
      "reps",
      "chunk_size",
      "save_dir",
      "simulate_one_cluster",
      "simulate_dataset",
      "make_label",
      "simulate_replicates",
      "run_one_grid_scenario"
    ),
    envir = .GlobalEnv
  )
  
  
  # -----------------------------------------------------------------------------------------------
  # Run grid scenarios
  # -----------------------------------------------------------------------------------------------
  
  out <- parallel::parLapply(
    cl,
    seq_len(nrow(grid)),
    run_one_grid_scenario
  )
  
  
  return(out)
}


# ==================================================================================================
# 11. RUN PARALLEL SIMULATION
# ==================================================================================================

out_list <- run_parallel_simulation()


# ==================================================================================================
# 12. CREATE SIMULATION GRID INDEX
# ==================================================================================================

grid_index <- do.call(
  rbind,
  out_list
)


# ==================================================================================================
# 14. SAVE SIMULATION GRID INDEX
# ==================================================================================================

saveRDS(
  grid_index,
  file.path(
    save_dir,
    "simulation_grid_index.rds"
  )
)

